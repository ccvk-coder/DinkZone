export function Icon({ name, className = 'h-4 w-4', ...props }) {
  const key = typeof name === 'string' ? name.replace(/^lucide:/, '') : '';
  const Glyph = registry[key] || Circle;
  const labelled = props['aria-label'] || props.role === 'img';
  return <Glyph className={className} aria-hidden={labelled ? undefined : true} {...props} />;
}
